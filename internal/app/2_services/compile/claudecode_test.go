func chosen(address string, kind string, id string, enforcement string, files map[string]string) resolve.Chosen {
	level := address[:strings.LastIndex(address[:strings.LastIndex(address, ".")], ".")]
	return resolve.Chosen{Declaration: resolve.Declaration{Address: address, Level: level, Kind: kind, ID: id, Selectors: declaration.Selectors{Enforcement: enforcement}, Files: files}}
}

func TestClaudeCode(t *testing.T) {
	result := resolve.Result{Chosen: []resolve.Chosen{
		chosen("organizations.acme.rules.style", "rules", "style", "required", map[string]string{"style.md": "---\nenforcement: required\n---\nHouse style.\n"}),
		chosen("organizations.acme.rules.go", "rules", "go", "", map[string]string{"go.md": "---\npaths: [\"**/*.go\"]\napplyIf: [language:go]\n---\nTwo-line errors.\n"}),
		chosen("organizations.acme.teams.web.rules.testing", "rules", "testing", "", map[string]string{"testing.md": "Web tests.\n"}),
		chosen("organizations.acme.skills.commit", "skills", "commit", "", map[string]string{"SKILL.md": "---\nname: commit\ndescription: Draft commits.\n---\n", "extra.md": "more"}),
		chosen("organizations.acme.hooks.gofmt", "hooks", "gofmt", "", map[string]string{"hook.yaml": "format: claude-code\nevent: PreToolUse\nmatcher: Bash\nrun: run.sh\ntimeout_seconds: 5\n", "run.sh": "#!/bin/sh\ngofmt -l .\n"}),
		chosen("organizations.acme.permissions.safety", "permissions", "safety", "required", map[string]string{"safety.yaml": "format: claude-code\ndeny: [\"Bash(git push --force*)\"]\nallow: [\"Bash(go test*)\"]\n"}),
		chosen("organizations.acme.mcpservers.github", "mcpservers", "github", "", map[string]string{"github.yaml": "transport: stdio\ncommand: npx\nargs: [\"-y\", \"server\"]\nenv:\n  GITHUB_PERSONAL_ACCESS_TOKEN: ${REIN_GITHUB_TOKEN}\nvariables:\n  REIN_GITHUB_TOKEN: a token\n"}),
		chosen("organizations.acme.mcpservers.docs", "mcpservers", "docs", "", map[string]string{"docs.yaml": "transport: http\nurl: https://docs.example/mcp\n"}),
		chosen("users.danidani23.rules.mine", "rules", "mine", "", map[string]string{"mine.md": "Mine.\n"}),
	}}
	input := Input{OrganizationSlug: "acme", ProjectName: "Shop", ProjectSlug: "shop", Teams: []string{"web"}, UserSlug: "danidani23", ReinExecutable: "/usr/local/bin/rein", ExistingSettings: `{"permissions":{"allow":["Bash(git push --force origin main)","Read(docs/**)"],"additionalDirectories":["../shared"]},"model":"opus"}`}
	output, err := ClaudeCode(input, result)
	if err != nil {
		t.Fatalf("compile: %v", err)
	}
	files := map[string]string{}
	for _, file := range output.Files {
		files[file.Path] = file.Content
	}
	for _, expected := range []string{"CLAUDE.md", ".claude/rein/organization.md", ".claude/rein/team-web.md", ".claude/rein/user.md", ".claude/rules/go.md", ".claude/skills/commit/SKILL.md", ".claude/skills/commit/extra.md", ".claude/hooks/gofmt/run.sh", ".claude/settings.local.json", ".mcp.json"} {
		if _, found := files[expected]; !found {
			t.Fatalf("missing %s in %v", expected, keys(files))
		}
	}
	claude := files["CLAUDE.md"]
	if !strings.HasPrefix(claude, "<!-- Generated by rein sync") || !strings.Contains(claude, "@.claude/rein/organization.md\n@.claude/rein/team-web.md\n@.claude/rein/user.md\n") || !strings.Contains(claude, "the higher level wins") {
		t.Fatalf("CLAUDE.md %q", claude)
	}
	if !strings.Contains(files[".claude/rein/organization.md"], "# Organisation acme\n\n## style\n\n<!-- organizations.acme.rules.style, required -->\nHouse style.") || strings.Contains(files[".claude/rein/organization.md"], "Two-line") {
		t.Fatalf("organization.md %q", files[".claude/rein/organization.md"])
	}
	if !strings.HasPrefix(files[".claude/rules/go.md"], "---\npaths:\n    - '**/*.go'\n---\n") || strings.Contains(files[".claude/rules/go.md"], "applyIf") {
		t.Fatalf("go.md %q", files[".claude/rules/go.md"])
	}
	var settings map[string]any
	err = json.Unmarshal([]byte(files[".claude/settings.local.json"]), &settings)
	if err != nil {
		t.Fatalf("settings: %v", err)
	}
	permissions := settings["permissions"].(map[string]any)
	if settings["model"] != "opus" || permissions["additionalDirectories"] == nil || strings.Join(toStrings(permissions["allow"]), ",") != "Bash(go test*),Read(docs/**)" || strings.Join(toStrings(permissions["deny"]), ",") != "Bash(git push --force*)" {
		t.Fatalf("permissions %+v notes %v", permissions, output.Notes)
	}
	if len(output.Notes) != 1 || !strings.Contains(output.Notes[0], "dropped") {
		t.Fatalf("notes %v", output.Notes)
	}
	hooks := settings["hooks"].(map[string]any)
	encodedHooks, _ := json.Marshal(hooks)
	if !strings.Contains(string(encodedHooks), `"SessionStart"`) || !strings.Contains(string(encodedHooks), `\"/usr/local/bin/rein\" sync --hook`) || !strings.Contains(string(encodedHooks), `\"$CLAUDE_PROJECT_DIR\"/.claude/hooks/gofmt/run.sh`) || !strings.Contains(string(encodedHooks), `"timeout":5`) {
		t.Fatalf("hooks %s", encodedHooks)
	}
	var mcp map[string]map[string]map[string]any
	_ = json.Unmarshal([]byte(files[".mcp.json"]), &mcp)
	if mcp["mcpServers"]["github"]["command"] != "npx" || mcp["mcpServers"]["github"]["type"] != nil || mcp["mcpServers"]["docs"]["type"] != "http" || strings.Join(output.Variables, ",") != "REIN_GITHUB_TOKEN" {
		t.Fatalf("mcp %+v variables %v", mcp, output.Variables)
	}
	empty, _ := ClaudeCode(Input{OrganizationSlug: "acme", ProjectName: "Bare", ProjectSlug: "bare"}, resolve.Result{})
	if len(empty.Files) != 2 || !strings.Contains(empty.Files[0].Content+empty.Files[1].Content, "No always-on instructions apply") {
		t.Fatalf("empty %+v", empty.Files)
	}
}

func keys(files map[string]string) []string {
	var list []string
	for key := range files {
		list = append(list, key)
	}
	return list
}

func toStrings(raw any) []string {
	var list []string
	for _, item := range raw.([]any) {
		list = append(list, item.(string))
	}
	return list
}
